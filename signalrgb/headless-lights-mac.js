// headless-lights: bridge the SignalRGB canvas to the peripherals attached to
// the Mac.
//
// SignalRGB runs on the PC; the K70 MAX, MM700, G560 and Scimitar are plugged
// into a Mac on the same desk. The Mac runs mac-agent, which normally renders
// its own effects. This plugin instead streams the canvas to it, one frame per
// device, over a TCP connection tunnelled through SSH:
//
//     ssh -N -L 7532:127.0.0.1:7532 mac
//
// So the plugin always talks to 127.0.0.1:7532 on the PC, and nothing new is
// exposed on the LAN. The wire format is documented in mac-agent/README.md and
// defined in mac-agent/stream_protocol.h.
//
// The K70 tables below are generated from mac-agent/k70max_layout.h by
// tools/gen_k70_layout.py. Run it after changing that header.

