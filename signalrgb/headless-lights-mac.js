export function Initialize() {
	device.log(`headless-lights: Initialize model=${controller.model}`);
	config = DEVICES[controller.model];
	if (config === undefined) {
		device.log(`unknown controller model "${controller.model}"`);
		return;
	}

	device.setName(config.name);
	device.setSize(config.size);
	device.setControllableLeds(config.ledNames, config.ledPositions);
	if (typeof device.setImageFromResource === "function" && config.image) {
		device.setImageFromResource(config.image);
	}

	lastSendAt = 0;

	// SignalRGB 2.5.74 contains an internal TCP factory but does not expose it
	// to plugins: the global is undefined and @SignalRGB/tcp is not resolvable.
	// UDP is a supported device feature, so send to a loopback bridge which
	// forwards the unchanged frame into the TCP SSH tunnel to the Mac.
	device.addFeature("udp");
}

export function Render() {
	if (config === null) {
		return;
	}
	// The agent paces writes anyway; there is no point pushing 60fps of every
	// device through the tunnel.
	const now = Date.now();
	if (now - lastSendAt < config.intervalMs) {
		return;
	}
	lastSendAt = now;

	// Same binary frame as the Mac consumes over TCP. UDP preserves packet
	// bytes and boundaries on loopback; the local bridge unwraps it into the
	// SSH-forwarded TCP stream.
	udp.send(STREAM_HOST, STREAM_PORT, buildFrame(config, readCanvas(config)), false);
}

export function Shutdown() {
	// Deliberately no black frame: when datagrams stop, the agent's 3s timeout
	// hands the devices back to the Mac's own effect.
	config = null;
}

// Returns one [r,g,b] per wire slot, black for slots with no physical LED.
function readCanvas(target) {
	const slots = new Array(target.wireSlots);
	for (let slot = 0; slot < target.wireSlots; slot++) {
		slots[slot] = [0, 0, 0];
	}

	const forced = LightingMode === "Forced" ? hexToRgb(forcedColor) : null;
	const positions = target.ledPositions;
	for (let led = 0; led < positions.length; led++) {
		const slot = target.wireIndex === null ? led : target.wireIndex[led];
		if (forced !== null) {
			slots[slot] = forced;
			continue;
		}
		const color = device.color(positions[led][0], positions[led][1]);
		slots[slot] = [color[0], color[1], color[2]];
	}
	return slots;
}

// Returns a plain array of byte values, never a string. Measured: a 256-byte
// ramp sent as a JS string survives only if the runtime encodes it as latin1;
// as UTF-8 every byte >= 0x80 becomes two (0x80 -> c2 80), which would turn a
// 432-byte K70 frame into as much as 640 bytes of garbage. An array has no such
// ambiguity.
function buildFrame(target, slots) {
	const payloadLength = target.wireSlots * 3;
	const packet = [
		MAGIC_0,
		MAGIC_1,
		PROTOCOL_VERSION,
		target.deviceId,
		payloadLength & 0xff,
		(payloadLength >> 8) & 0xff,
	];
	for (let slot = 0; slot < slots.length; slot++) {
		packet.push(slots[slot][0], slots[slot][1], slots[slot][2]);
	}
	return packet;
}

function hexToRgb(hex) {
	const parsed = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
	if (parsed === null) {
		return [0, 0, 0];
	}
	return [
		parseInt(parsed[1], 16),
		parseInt(parsed[2], 16),
		parseInt(parsed[3], 16),
	];
}

export function DiscoveryService() {
	this.IconUrl = "default/keyboard";
	this.announced = false;

	this.Initialize = function () {
		// addController is not safe while SignalRGB is still constructing this
		// discovery service: it persists the object but does not create a device
		// engine. Official add-ons discover asynchronously, after Initialize has
		// returned. Do the deterministic registration on the first Update tick.
		service.log("headless-lights: waiting for first discovery update");
	};

	this.Update = function () {
		this.EnsureControllers();
		for (const entry of service.controllers) {
			entry.obj.update();
		}
	};

	// The bridge is always reached on UDP loopback, so there is nothing to
	// discover and nothing for the user to configure.
	this.EnsureControllers = function () {
		if (this.announced) {
			return;
		}
		this.announced = true;
		for (const model of Object.keys(DEVICES)) {
			const legacy = service.getController(`headless-lights-${model}`);
			if (legacy !== undefined) {
				service.removeController(legacy);
			}

			// The first development build crashed its engine threads under the
			// old headless-lights-* ids. SignalRGB quarantines a crashing engine by
			// id across restarts, so use the repository name as the stable identity.
			const value = {
				id: `signalrgb-mac-bridge-${model}`,
				name: DEVICES[model].name,
				ip: STREAM_HOST,
				hostname: "localhost",
				port: STREAM_PORT,
				model: model,
				firmwareVersion: "1.0.0",
			};
			const existing = service.getController(value.id);
			if (existing !== undefined) {
				// Controllers survive app restarts, but their device engine threads
				// do not. Reusing the persisted object does not recreate an engine in
				// SignalRGB 2.5. Remove it and follow the same fresh-registration path
				// that works on first install.
				service.removeController(existing);
			}
			// Register first, then follow the bundled WLED bridge's save/update/
			// announce lifecycle. The discovery service receives only its startup
			// Update in SignalRGB 2.5 for this deterministic service, so waiting for
			// another tick leaves the object persisted but never creates an engine.
			const created = new MacBridgeController(value);
			service.addController(created);
			created.announce();
		}
	};
}

class MacBridgeController {
	constructor(value) {
		// Match SignalRGB's own WLED lifecycle: do not call updateController
		// before addController has registered this object.
		this.updateWithValue(value);
		// Loopback through the SSH tunnel is the transport boundary; unlike a
		// discovered Wi-Fi device there is no pairing/link step. The controller
		// must be connected when announced or SignalRGB persists it without
		// starting a device engine.
		this.connected = true;
		this.announced = false;
	}

	updateWithValue(value) {
		this.id = value.id;
		this.name = value.name;
		this.ip = value.ip;
		this.hostname = value.hostname;
		this.port = value.port;
		this.model = value.model;
		this.firmwareVersion = value.firmwareVersion;
	}

	update() {
		if (!this.announced) {
			this.announce();
		}
	}

	announce() {
		if (this.announced) {
			return;
		}
		// The official WLED bridge persists these two fields before announcing a
		// freshly discovered network controller. Follow that exact path.
		service.saveSetting(this.id, "name", this.name);
		service.saveSetting(this.id, "ip", this.ip);
		service.updateController(this);
		service.announceController(this);
		this.announced = true;
		service.updateController(this);
	}
}

